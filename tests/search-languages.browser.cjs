const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 fs.mkdirSync('test-results',{recursive:true});
 const data=fs.mkdtempSync(path.resolve('test-results/languages-'));
 const server=spawn('python',['tests/browser_server.py'],{env:{...process.env,APP_PORT:'8793',APP_DATA_DIR:data,SMTP_HOST:'',SMTP_FROM:'',IMAP_HOST:'',OPENAI_API_KEY:'',HUNTER_API_KEY:'browser-fixture-only'},stdio:'pipe'});
 let browser;
 try{
  await new Promise((resolve,reject)=>{server.stdout.on('data',d=>{if(d.toString().includes('Katie:'))resolve()});server.on('error',reject);server.on('exit',c=>reject(Error('Server exit '+c)));setTimeout(()=>reject(Error('Server timeout')),10000).unref()});
  browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  await page.addInitScript(()=>localStorage.setItem('kaska-simulation','off'));
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:8793');
  await page.waitForFunction(()=>state?.seller_profile);
  await page.locator('nav [data-view=prospecting]').click();
  await page.locator('#prospect-website').fill('alpha.example');
  await page.locator('#prospect-offer').fill('Logistics services');
  await page.locator('#prospect-audience').fill('Retail companies operating online stores');
  await page.locator('#prospect-language').selectOption('fr');
  await page.locator('[data-search-language-picker] summary').click();
  assert.equal(await page.locator('[name=search_language]').count(),6);
  await page.locator('[name=search_language][value=en]').check();
  await page.locator('[name=search_language][value=de]').check();
  assert.equal(await page.locator('[data-search-languages-summary]').textContent(),'English, Deutsch');
  const requestPromise=page.waitForRequest(r=>r.url().endsWith('/api/prospecting/search'));
  await page.locator('#prospect-search').click();
  const body=(await requestPromise).postDataJSON();
  assert.deepEqual(body.search_languages,['en','de']);assert.equal(body.language,'fr');
  await page.waitForFunction(()=>state.prospecting.runs[0]?.status==='ready');
  assert.deepEqual(await page.evaluate(()=>JSON.parse(state.prospecting.runs[0].search_languages)),['en','de']);
  assert.equal(await page.evaluate(()=>state.prospecting.runs[0].language),'fr');
  await page.locator('nav [data-view=discover]').click();
  await page.locator('#discover-profile').evaluate(el=>el.open=true);
  assert.equal(await page.locator('[name=search_language][value=en]').isChecked(),true);
  assert.equal(await page.locator('[name=search_language][value=de]').isChecked(),true);
  await page.reload();
  await page.getByRole('heading',{name:'Odkrywanie firm',exact:true}).waitFor();
  assert.equal(await page.locator('[name=search_language][value=de]').isChecked(),true);
  await page.locator('nav [data-view=prospecting]').click();
  await page.locator('[data-search-language-picker] summary').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-search-language-picker]').scrollIntoViewIfNeeded();
  await page.screenshot({path:'test-results/search-languages-mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('[data-search-languages-clear]').click();
  await page.evaluate(async()=>flushSellerProfile());
  assert.deepEqual(await page.evaluate(()=>state.seller_profile.search_languages),[]);
  await page.evaluate(async()=>{await api('seller-profiles/create',{name:'Other language profile'});await refresh()});
  assert.equal(await page.locator('[name=search_language]:checked').count(),0);
  await page.locator('[data-search-language-picker] summary').click();
  await page.locator('[name=search_language][value=it]').check();
  await page.locator('#active-profile').selectOption('1');
  await page.waitForFunction(()=>!sellerSwitchBusy&&state.seller_profile.id===1);
  assert.equal(await page.locator('[name=search_language]:checked').count(),0);
  await page.locator('#ui-language').selectOption('en');
  await page.locator('[data-search-language-picker]').getByText('Search in languages',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('Search languages QA passed: six checkboxes, multiple selection, search payload, independent message language, profile persistence, clear, isolation, English and mobile.');
 }finally{if(browser)await browser.close();server.kill()}
})().catch(e=>{console.error(e);process.exitCode=1});
