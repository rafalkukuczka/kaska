const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 fs.mkdirSync('test-results',{recursive:true});
 const data=fs.mkdtempSync(path.resolve('test-results/audience-'));
 const server=spawn('python',['tests/browser_server.py'],{env:{...process.env,APP_PORT:'8794',APP_DATA_DIR:data,SMTP_HOST:'',SMTP_FROM:'',IMAP_HOST:'',OPENAI_API_KEY:'',HUNTER_API_KEY:'browser-fixture-only'},stdio:'pipe'});
 let browser,release;
 try{
  await new Promise((resolve,reject)=>{server.stdout.on('data',d=>{if(d.toString().includes('Katie:'))resolve()});server.on('error',reject);server.on('exit',c=>reject(Error('Server exit '+c)));setTimeout(()=>reject(Error('Server timeout')),10000).unref()});
  browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],calls=[],searches=[];
  await page.addInitScript(()=>localStorage.setItem('kaska-simulation','off'));
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().endsWith('/api/prospecting/search'))searches.push(r.url())});
  await page.route('**/api/state',async route=>{const response=await route.fetch(),snapshot=await response.json();snapshot.integrations.ai=true;await route.fulfill({response,json:snapshot})});
  let fail=false,hold=false;
  await page.route('**/api/ai/suggest-audience',async route=>{
   calls.push(route.request().postDataJSON());
   if(hold)await new Promise(resolve=>release=resolve);
   await route.fulfill({status:fail?400:200,json:fail?{error:'AI fixture failure'}:{audience:'Manufacturing companies using manual reporting, excluding retailers.'}});
  });
  await page.goto('http://localhost:8794');await page.waitForFunction(()=>state?.seller_profile);
  await page.locator('nav [data-view=prospecting]').click();
  const tuneBounds=await page.locator('[data-refine=audience]').boundingBox(),suggestBounds=await page.locator('[data-suggest-audience]').boundingBox(),mapBounds=await page.locator('[data-show-search-map]').boundingBox();
  assert.ok(Math.abs(tuneBounds.y-suggestBounds.y)<2);
  assert.ok(mapBounds.y>suggestBounds.y+suggestBounds.height);
  await page.locator('#prospect-offer').fill('Industrial automation');
  await page.locator('[data-point-editor=pain_points] .point-row input').first().fill('Manual reporting');
  await page.locator('[data-point-editor=value_props] .point-row input').first().fill('Less repetitive work');
  await page.locator('#prospect-audience').fill('Original audience excluding retailers');
  await page.locator('[data-suggest-audience]').click();
  await page.locator('[data-audience-proposal]').waitFor();
  assert.equal(calls[0].offer,'Industrial automation');assert.equal(calls[0].pain_points,'Manual reporting');assert.equal(calls[0].value_props,'Less repetitive work');
  assert.equal(await page.locator('#prospect-audience').inputValue(),'Original audience excluding retailers');
  await page.locator('[data-audience-text]').fill('My edited manufacturing company filter');
  await page.locator('[data-audience-apply]').click();
  assert.equal(await page.locator('#prospect-audience').inputValue(),'My edited manufacturing company filter');
  await page.evaluate(async()=>flushSellerProfile());
  assert.equal(await page.evaluate(()=>state.seller_profile.audience),'My edited manufacturing company filter');
  await page.locator('[data-audience-undo]').click();
  assert.equal(await page.locator('#prospect-audience').inputValue(),'Original audience excluding retailers');
  hold=true;
  await page.locator('[data-suggest-audience]').click();await page.waitForFunction(()=>document.querySelector('[data-suggest-audience]').disabled);
  await page.waitForTimeout(100);
  await page.locator('#prospect-audience').fill('User changed description while waiting');
  release();hold=false;
  await page.locator('[data-audience-proposal]').waitFor();
  assert.equal(await page.locator('#prospect-audience').inputValue(),'User changed description while waiting');
  await page.locator('[data-audience-dismiss]').click();
  fail=true;
  await page.locator('[data-suggest-audience]').click();
  await page.waitForFunction(()=>!document.querySelector('[data-suggest-audience]').disabled);
  assert.equal(await page.locator('#prospect-audience').inputValue(),'User changed description while waiting');
  fail=false;
  await page.locator('nav [data-view=discover]').click();
  await page.locator('#discover-profile').evaluate(el=>el.open=true);
  assert.equal(await page.locator('#prospect-audience').inputValue(),'User changed description while waiting');
  await page.locator('[data-suggest-audience]').click();await page.locator('[data-audience-proposal]').waitFor();
  await page.locator('[data-audience-apply]').click();await page.evaluate(async()=>flushSellerProfile());
  await page.reload();await page.waitForFunction(()=>state?.seller_profile);
  await page.locator('#discover-profile').evaluate(el=>el.open=true);
  assert.equal(await page.locator('#prospect-audience').inputValue(),'Manufacturing companies using manual reporting, excluding retailers.');
  // A late answer for another profile must never appear in the new profile.
  hold=true;release=null;
  await page.locator('[data-suggest-audience]').click();
  while(!release)await new Promise(resolve=>setTimeout(resolve,10));
  await page.evaluate(async()=>chooseSellerProfile('seller-profiles/create',{name:'Another profile'}));
  release();hold=false;
  await page.waitForFunction(()=>!document.querySelector('[data-audience-proposal]')||document.querySelector('[data-audience-proposal]').hidden);
  assert.equal(await page.locator('#prospect-audience').inputValue(),'');
  assert.deepEqual(searches,[]);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'test-results/audience-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log('Audience AI QA passed: offer/pains/values context, review/edit/apply/undo/discard, concurrent edits, errors, shared persistence, profile isolation, no automatic search, mobile.');
 }finally{if(release)release();if(browser)await browser.close();server.kill()}
})().catch(e=>{console.error(e);process.exitCode=1});
